#!/usr/bin/env python3
"""Versioned `LV_SYMBOL_*` code point map shared by the host contracts.

`managed_components/` is gitignored (`.gitignore`) and the CI host aggregate
runs *before* `install-esp-idf-action`, so a clean checkout has no
`managed_components/lvgl__lvgl/include/lvgl/font/lv_symbol_def.h`. Reading that
header directly from a contract therefore turned every push red with
`FileNotFoundError`. The contract now resolves the macros from
`lv_symbol_codepoints.json`, which is generated from the pinned header and
versioned with the tests.

The generated JSON is only re-validated against the real header outside the
aggregate: `make -C tests/host/keymap verify_lv_symbol_codepoints` re-parses
`lv_symbol_def.h` when `managed_components` is materialized and fails on drift;
when the header is absent it prints `SKIP` and exits 0.

`--strict` turns that skip into a failure, so a CI environment that silently
fails to materialize `managed_components` cannot turn the drift gate into a
green no-op:

    python3 tests/host/keymap/lv_symbol_map.py --verify --strict

Regenerate the versioned map after bumping LVGL:

    python3 tests/host/keymap/lv_symbol_map.py --write
"""

from pathlib import Path
import json
import re
import sys

ROOT = Path(__file__).resolve().parents[3]
HEADER = (ROOT / "managed_components/lvgl__lvgl/include/lvgl/font"
          "/lv_symbol_def.h")
MAP = Path(__file__).resolve().with_name("lv_symbol_codepoints.json")
SOURCE = "managed_components/lvgl__lvgl/include/lvgl/font/lv_symbol_def.h"

# `LV_SYMBOL_*` glyphs are Font Awesome code points in the private use block;
# `LV_SYMBOL_BULLET` is the only plain Unicode symbol shipped by the header.
FONT_AWESOME_RANGE = (0xF000, 0xF8FF)
NON_FONT_AWESOME = {"LV_SYMBOL_BULLET": 0x2022}
# Anti-truncation floor: the pinned LVGL 9.6 header defines 62 symbols.
MIN_SYMBOLS = 60

DEFINE = re.compile(
    r'#define\s+(LV_SYMBOL_[A-Z0-9_]+)\s+"([^"\n]*)"')
# Only `\xHH` escapes are accepted. A raw (UTF-8) glyph inside the literal would
# otherwise be dropped silently, which is why the body is validated before it is
# decoded instead of being matched by the escape pattern alone.
ESCAPED_BODY = re.compile(r"^(?:\\x[0-9A-Fa-f]{2})+$")
NAME_PATTERN = re.compile(r"^LV_SYMBOL_[A-Z0-9_]+$")


class SymbolMapError(AssertionError):
    """The versioned map is structurally invalid (not merely outdated)."""


def strip_comments(text: str) -> str:
    """Drop `//` and `/* */` comments so commented defines cannot be parsed."""
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    return re.sub(r"//[^\n]*", "", text)


def hex_label(codepoint: int) -> str:
    return f"U+{codepoint:04X}"


def macro_codepoint(name: str, escaped: str) -> int:
    """Decode the single-glyph literal of one `#define LV_SYMBOL_*` body.

    Fail closed with an explainable error: a body that is not a pure `\\xHH`
    escape sequence, that is not valid UTF-8, or that decodes to more than one
    code point would otherwise be dropped by `ord()` or ignored silently.
    """
    if not escaped:
        raise SymbolMapError(f"{name}: empty macro body; expected a \\xHH escape")
    if not ESCAPED_BODY.match(escaped):
        raise SymbolMapError(
            f"{name}: macro body {escaped!r} is not a pure \\xHH escape sequence; "
            "an unescaped (UTF-8) literal would be ignored silently")
    raw = bytes(int(value, 16)
                for value in re.findall(r"\\x([0-9A-Fa-f]{2})", escaped))
    try:
        text = raw.decode("utf-8")
    except UnicodeDecodeError as error:
        raise SymbolMapError(
            f"{name}: macro body {escaped!r} is not valid UTF-8 ({error.reason})"
        ) from None
    if len(text) != 1:
        raise SymbolMapError(
            f'{name}: macro body "{escaped}" decodes to {len(text)} code points '
            f"({text!r}); exactly one glyph is required")
    return ord(text)


def parse_symbols(header: str) -> dict[str, int]:
    """Map every `LV_SYMBOL_*` macro of the header to its code point.

    The literal UTF-8 escape bytes are what the compiler sees, so the trailing
    `/*61441, 0xF001*/` comment of each macro is not trusted (upstream already
    ships a stale one).
    """
    symbols: dict[str, int] = {}
    for name, escaped in DEFINE.findall(strip_comments(header)):
        symbols[name] = macro_codepoint(name, escaped)
    return symbols


def render_json(symbols: dict[str, int]) -> str:
    entries = ",\n".join(
        f'    {json.dumps(name)}: {{"codepoint": {symbols[name]}, '
        f'"hex": "{hex_label(symbols[name])}"}}'
        for name in sorted(symbols))
    return (
        "{\n"
        f'  "source": "{SOURCE}",\n'
        '  "note": "Generated by lv_symbol_map.py --write from the pinned LVGL '
        'header; never hand-edit code points.",\n'
        '  "symbols": {\n'
        f"{entries}\n"
        "  }\n"
        "}\n")


def _unique_pairs(pairs: list[tuple[str, object]]) -> dict[str, object]:
    unique: dict[str, object] = {}
    for key, value in pairs:
        if key in unique:
            raise SymbolMapError(f"duplicate key in the symbol map: {key}")
        unique[key] = value
    return unique


def parse_map(text: str) -> dict[str, int]:
    """Parse and structurally validate the versioned map text."""
    data = json.loads(text, object_pairs_hook=_unique_pairs)
    if not isinstance(data, dict) or not isinstance(data.get("symbols"), dict):
        raise SymbolMapError("the map must contain a 'symbols' object")
    symbols: dict[str, int] = {}
    for name, entry in data["symbols"].items():
        if not isinstance(entry, dict):
            raise SymbolMapError(f"{name}: entry must be an object")
        codepoint = entry.get("codepoint")
        label = entry.get("hex")
        if not isinstance(codepoint, int) or isinstance(codepoint, bool):
            raise SymbolMapError(f"{name}: 'codepoint' must be an integer")
        if not isinstance(label, str) or not label:
            raise SymbolMapError(f"{name}: 'hex' must be a non-empty string")
        if label != hex_label(codepoint):
            raise SymbolMapError(
                f"{name}: 'hex' {label} disagrees with codepoint {codepoint}")
        symbols[name] = codepoint
    return symbols


def load_symbols(path: Path = MAP) -> dict[str, int]:
    """Load and structurally validate the versioned map file."""
    return parse_map(path.read_text(encoding="utf-8"))


def map_issues(symbols: dict[str, int]) -> list[str]:
    """Sanity issues of a loaded map: names, ranges and non-vacuity."""
    issues: list[str] = []
    if len(symbols) < MIN_SYMBOLS:
        issues.append(
            f"the map must keep at least {MIN_SYMBOLS} symbols "
            f"(found {len(symbols)})")
    for name, codepoint in sorted(symbols.items()):
        if not NAME_PATTERN.match(name):
            issues.append(f"invalid symbol name: {name!r}")
            continue
        low, high = FONT_AWESOME_RANGE
        expected = NON_FONT_AWESOME.get(name)
        if expected is not None:
            if codepoint != expected:
                issues.append(
                    f"{name} must stay {hex_label(expected)}, "
                    f"found {hex_label(codepoint)}")
        elif not low <= codepoint <= high:
            issues.append(
                f"{name} ({hex_label(codepoint)}) is outside the Font Awesome "
                f"block {hex_label(low)}..{hex_label(high)}")
    return issues


def verify(header: Path = HEADER, path: Path = MAP, strict: bool = False) -> int:
    """Compare the versioned map against the pinned header when present.

    Without the pinned header the check is impossible: a local run prints
    `SKIP` and exits 0, while `strict` (used by CI) exits non-zero so a missing
    `managed_components/` cannot turn the drift gate into a green no-op.
    """
    if not header.is_file():
        if strict:
            print(f"FAIL: {SOURCE} is absent; the strict drift gate cannot verify "
                  "the versioned code points (materialize managed_components "
                  "before running it)")
            return 1
        print("SKIP: lv_symbol_def.h ausente (managed_components não materializado)")
        return 0
    expected = parse_symbols(header.read_text(encoding="utf-8"))
    actual = load_symbols(path)
    issues = [f"{name}: missing from lv_symbol_codepoints.json"
              for name in sorted(set(expected) - set(actual))]
    issues += [f"{name}: stale entry, no longer defined by lv_symbol_def.h"
               for name in sorted(set(actual) - set(expected))]
    issues += [f"{name}: versioned {hex_label(actual[name])} but the header "
               f"defines {hex_label(expected[name])}"
               for name in sorted(set(expected) & set(actual))
               if expected[name] != actual[name]]
    if issues:
        for issue in issues:
            print(f"FAIL: {issue}")
        print("FAIL: lv_symbol_codepoints.json drifted from lv_symbol_def.h; "
              "regenerate with `python3 tests/host/keymap/lv_symbol_map.py --write`")
        return 1
    print(f"PASS: lv_symbol_codepoints.json matches {SOURCE} "
          f"({len(expected)} symbols)")
    return 0


def write_map(path: Path = MAP) -> int:
    """Regenerate the versioned map from the pinned header."""
    if not HEADER.is_file():
        print(f"FAIL: {SOURCE} is absent; nothing to regenerate")
        return 1
    symbols = parse_symbols(HEADER.read_text(encoding="utf-8"))
    issues = map_issues(symbols)
    if issues:
        for issue in issues:
            print(f"FAIL: {issue}")
        return 1
    path.write_text(render_json(symbols), encoding="utf-8")
    print(f"WROTE: {path.name} ({len(symbols)} symbols)")
    return 0


def main(argv: list[str]) -> int:
    strict = "--strict" in argv
    args = [argument for argument in argv if argument != "--strict"]
    if args == ["--write"] and strict:
        print("FAIL: --strict only applies to --verify")
        return 2
    if args not in ([], ["--verify"], ["--write"]):
        print(f"FAIL: unknown arguments {argv}")
        return 2
    try:
        if args == ["--write"]:
            return write_map()
        return verify(strict=strict)
    except SymbolMapError as error:
        print(f"FAIL: the versioned symbol map is invalid: {error}")
        return 1
    except json.JSONDecodeError as error:
        print(f"FAIL: {MAP.name} is not valid JSON (line {error.lineno}, "
              f"column {error.colno}): {error.msg}")
        return 1
    except UnicodeDecodeError as error:
        print(f"FAIL: a file read by the gate is not valid UTF-8: {error.reason}")
        return 1
    except FileNotFoundError as error:
        print(f"FAIL: required file is missing: {error.filename or error}")
        return 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
